"""Router for summary generation endpoint."""

import logging
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session
from app.database import get_db
from app.services.retrieval import SummaryService
from app.services.summary import generate_summary, generate_summary_stream, SAFE_DISCLAIMER
from app.schemas import SummaryRequest, SummaryResponse

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/patients", tags=["summary"])


@router.post("/{patient_id}/summary", response_model=SummaryResponse)
def generate_patient_summary(
    patient_id: str,
    request: SummaryRequest = SummaryRequest(),
    db: Session = Depends(get_db),
):
    """Generate clinical summary from retrieved records with optional LLM support."""
    try:
        # Get summary context (all records for patient)
        context = SummaryService.get_summary_context(
            db,
            patient_id,
            max_encounters=request.max_encounters,
        )
        
        if not context:
            raise HTTPException(status_code=404, detail="Patient not found or no records available")

        # Generate summary (LLM or template)
        summary_text, mode = generate_summary(context, use_llm=True, focus_test=request.focus_test)

        # Get evidence references
        evidence_refs = SummaryService.get_evidence_references(context)

        return {
            "patient_id": patient_id,
            "summary_text": summary_text,
            "evidence_references": evidence_refs,
            "mode": mode,
            "status": SAFE_DISCLAIMER,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error generating summary: {e}")
        raise HTTPException(status_code=500, detail=f"Error generating summary: {str(e)}")


@router.post("/{patient_id}/summary/stream")
def stream_patient_summary(
    patient_id: str,
    request: SummaryRequest = SummaryRequest(),
    db: Session = Depends(get_db),
):
    """
    Stream clinical summary as Server-Sent Events.
    Returns chunks of the summary as they're generated by the LLM.
    """
    try:
        # Get summary context
        context = SummaryService.get_summary_context(
            db,
            patient_id,
            max_encounters=request.max_encounters,
        )
        
        if not context:
            raise HTTPException(status_code=404, detail="Patient not found or no records available")

        async def event_generator():
            """Generate Server-Sent Events with summary chunks."""
            try:
                # Stream summary from LLM
                for chunk in generate_summary_stream(context, use_llm=True, focus_test=request.focus_test):
                    if chunk:  # Only send non-empty chunks
                        # Format as SSE event
                        yield f"data: {chunk}\n\n"
                
                # Signal completion
                yield "data: [DONE]\n\n"
                
            except Exception as e:
                logger.error(f"Error during streaming: {e}")
                # Send error event
                yield f"data: [ERROR:{str(e)}]\n\n"

        return StreamingResponse(
            event_generator(),
            media_type="text/event-stream",
            headers={
                "Cache-Control": "no-cache",
                "Connection": "keep-alive",
                "X-Accel-Buffering": "no",
            },
        )

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error in streaming endpoint: {e}")
        raise HTTPException(status_code=500, detail=f"Error initializing stream: {str(e)}")
